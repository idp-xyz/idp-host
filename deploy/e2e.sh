#!/usr/bin/env bash
# End-to-end on the compose topology: the HOST image, the real idp-mcp registry and gateway (their
# published image), two real MCP SDK upstreams and a model endpoint on the Docker host. From nothing
# each run: build image -> postgres -> migrations, service logins, tenants (both products) ->
# registry -> gateway record and container -> MCP provisioning (servers, grants, API key for the
# HOST, release, deploy) -> HOST container -> tests/e2e -> tear down (KEEP=1 leaves it running).
#   MODEL=fake (default)  the deterministic double (tests/fixtures/fakemodel) as a container
#   MODEL=live            IDP_E2E_MODEL_URL (OpenAI-compatible, reachable from containers) and
#                         IDP_E2E_MODEL_NAME; the assertions on exact wording are relaxed
#   MODE=apikey (default) the HOST calls the gateway with a static API key; HS256 development tokens
#   MODE=oidc             Keycloak: real users log in, the HOST verifies their tokens with the JWKS and
#                         calls the gateway (jwt mode) with RFC 8693 delegated tokens (act = idp-host)
set -euo pipefail
cd "$(dirname "$0")/.."
ENVF=.local/compose.env
C=(docker compose -f deploy/compose.yaml --env-file "$ENVF" --profile oidc)
MODEL="${MODEL:-fake}"
MODE="${MODE:-apikey}"
REG=http://127.0.0.1:8250
HOST=http://127.0.0.1:8450
ISSUER=http://127.0.0.1:7080/realms/idp
RESOURCE=http://mcp-gateway:3320/mcp   # the gateway's canonical MCP URI as the HOST calls it
CURL=(curl -sf --noproxy '*')
mkdir -p .local
umask 077
if [[ ! -f "$ENVF" ]]; then
  { echo "IDP_PG_OWNER_PASSWORD=$(openssl rand -hex 16)"
    echo "IDP_APP_DB_PASSWORD=$(openssl rand -hex 16)"
    echo "IDP_HOST_DB_PASSWORD=$(openssl rand -hex 16)"
    echo "IDP_DEV_ADMIN_SECRET=$(openssl rand -hex 32)"
    echo "IDP_DEV_SECRET=$(openssl rand -hex 32)"
    echo "IDP_HOST_CREDENTIAL_KEY=$(openssl rand -hex 32)"; } > "$ENVF"
fi
grep -q '^KC_BOOTSTRAP_ADMIN_PASSWORD=' "$ENVF" || printf 'KC_BOOTSTRAP_ADMIN_USERNAME=admin\nKC_BOOTSTRAP_ADMIN_PASSWORD=%s\n' "$(openssl rand -hex 16)" >> "$ENVF"
sed -i '/^IDP_GATEWAY_ID=/d; /^IDP_GATEWAY_TOKEN=/d' "$ENVF"
set -a; source "$ENVF"; set +a
TENANT_FIXED=""
if [[ "$MODE" == oidc ]]; then
  # one tenant id for both products: the user's tenant_id claim must satisfy the HOST and the gateway
  TENANT_FIXED="$(python3 -c 'import uuid; print(uuid.uuid4())')"
  rm -rf .local/keycloak && mkdir -p .local/keycloak && chmod 755 .local/keycloak
  python3 deploy/keycloak/realm.py .local/keycloak "$TENANT_FIXED" "$RESOURCE" .local/keycloak-clients.json
  export IDP_HOST_JWKS_URL=http://keycloak:7080/realms/idp/protocol/openid-connect/certs IDP_HOST_ISSUER="$ISSUER"
fi

for img in "${IDP_MCP_IMAGE:-idp-mcp:dev}" "${IDP_FIXTURE_IMAGE:-idp-fixture-upstream:local}"; do
  docker image inspect "$img" >/dev/null 2>&1 || { echo "BLOCKED: image $img missing (build it in the idp-mcp repository: deploy/build.sh idp-mcp:dev, deploy/fixtures/build.sh)" >&2; exit 2; }
done
bash deploy/build.sh idp-host:dev
"${C[@]}" down -v --remove-orphans >/dev/null 2>&1 || true
cleanup() { [[ "${KEEP:-0}" == 1 ]] || "${C[@]}" down -v --remove-orphans >/dev/null 2>&1; }
trap cleanup EXIT

SERVICES=(postgres minimal reference)
if [[ "$MODEL" == fake ]]; then
  bash deploy/fixtures/build-fakemodel.sh idp-host-fakemodel:dev
  SERVICES+=(fakemodel)
  MODEL_URL=http://fakemodel:18080/v1; MODEL_NAME=fake-1
else
  MODEL_URL="${IDP_E2E_MODEL_URL:?set IDP_E2E_MODEL_URL for MODEL=live}"; MODEL_NAME="${IDP_E2E_MODEL_NAME:?set IDP_E2E_MODEL_NAME}"
fi
umask 022
if [[ "$MODE" == oidc ]]; then
  # the HOST acts for the user: RFC 8693 delegation with its own client credentials as actor_token
  GW_AUTH="      mode: delegation
      tokenEndpoint: http://keycloak:7080/realms/idp/protocol/openid-connect/token
      clientId: idp-host
      clientSecretFile: /etc/idp/host.key
      audience: $RESOURCE
      actorToken: true"
else
  GW_AUTH="      mode: static
      apiKeyFile: /etc/idp/host.key"
fi
cat > .local/host.yaml <<EOF
# generated by deploy/e2e.sh (DEV ONLY, MODE=$MODE)
providers:
  - name: local
    kind: openai
    baseUrl: $MODEL_URL
    insecure: true
gateways:
  - name: edge
    endpoint: $RESOURCE
    auth:
$GW_AUTH
EOF
printf 'pending\n' > .local/host.key; chmod 644 .local/host.key
umask 077

[[ "$MODE" == oidc ]] && SERVICES+=(keycloak)
"${C[@]}" up -d --wait "${SERVICES[@]}"
if [[ "$MODE" == oidc ]]; then
  for _ in $(seq 1 90); do "${CURL[@]}" -o /dev/null "$ISSUER/.well-known/openid-configuration" && break; sleep 2; done
  python3 -I deploy/e2e_keycloak_setup.py http://127.0.0.1:7080 "${KC_BOOTSTRAP_ADMIN_USERNAME:-admin}" "$KC_BOOTSTRAP_ADMIN_PASSWORD"
fi
"${C[@]}" exec -T postgres psql -U postgres -q -c 'CREATE DATABASE idp_host' >/dev/null
"${C[@]}" run --rm -T registry-admin migrate
"${C[@]}" run --rm -T registry-admin ensure-login idp_mcp_svc
TENANT="$("${C[@]}" run --rm -T registry-admin seed-tenant acme $TENANT_FIXED | sed -n 's/^TENANT_ID=//p')"
"${C[@]}" run --rm -T host-admin migrate
"${C[@]}" run --rm -T host-admin ensure-login idp_host_svc
HTENANT="$("${C[@]}" run --rm -T host-admin seed-tenant acme $TENANT_FIXED | sed -n 's/^TENANT_ID=//p')"
[[ -n "$TENANT" && -n "$HTENANT" ]] || { echo "BLOCKED: no tenant" >&2; exit 2; }
"${C[@]}" up -d registry
for _ in $(seq 1 60); do "${CURL[@]}" -o /dev/null "$REG/api/v1/health" && break; sleep 0.5; done

ADMIN="$("${C[@]}" run --rm -T registry-admin dev-token "$TENANT" carol admin)"
OPERATOR="$("${C[@]}" run --rm -T registry-admin dev-token "$TENANT" alice operator)"
REVIEWER="$("${C[@]}" run --rm -T registry-admin dev-token "$TENANT" bob reviewer)"
if [[ "$MODE" == oidc ]]; then
  GW_BODY="{\"name\":\"edge-1\",\"authMode\":\"jwt\",\"jwt\":{\"issuer\":\"$ISSUER\",\"resource\":\"$RESOURCE\",\"jwksUrl\":\"http://keycloak:7080/realms/idp/protocol/openid-connect/certs\",\"tenantClaim\":\"tenant_id\",\"rolesClaim\":\"roles\"}}"
else
  GW_BODY='{"name":"edge-1","authMode":"api-key"}'
fi
GW="$("${CURL[@]}" -H "Authorization: Bearer $ADMIN" -H 'Content-Type: application/json' -d "$GW_BODY" "$REG/api/v1/gateways")"
GW_ID="$(python3 -c 'import json,sys; print(json.load(sys.stdin)["gateway"]["gatewayId"])' <<<"$GW")"
GW_TOKEN="$(python3 -c 'import json,sys; print(json.load(sys.stdin)["token"])' <<<"$GW")"
printf 'IDP_GATEWAY_ID=%s\nIDP_GATEWAY_TOKEN=%s\n' "$GW_ID" "$GW_TOKEN" >> "$ENVF"
"${C[@]}" up -d mcp-gateway
for _ in $(seq 1 60); do "${CURL[@]}" -o /dev/null http://127.0.0.1:3320/healthz && break; sleep 0.5; done

# servers, grants, the HOST's API key (static mode), release, deploy -> GOOD
KEY="$(python3 -I deploy/e2e_mcp_setup.py "$REG" "$GW_ID" "$ADMIN" "$OPERATOR" "$REVIEWER" "$MODE")"
if [[ "$MODE" == oidc ]]; then
  KEY="$(python3 -c 'import json; print(json.load(open(".local/keycloak-clients.json"))["idp-host"]["secret"])')"
fi
[[ -n "$KEY" ]] || { echo "BLOCKED: no credential for the HOST" >&2; exit 2; }
printf '%s\n' "$KEY" > .local/host.key; chmod 644 .local/host.key   # the HOST containers (uid 10001) read it
"${C[@]}" up -d host host-worker
for _ in $(seq 1 60); do "${CURL[@]}" -o /dev/null "$HOST/healthz" && break; sleep 0.5; done

echo "published ports: $(docker ps --filter label=com.docker.compose.project=idp-host-go --format '{{.Ports}}' | tr ',' '\n' | grep -- '->' | sed 's/^ *//' | sort -u | tr '\n' ' ')"
set +e
IDP_E2E_HOST="$HOST" IDP_E2E_HOST_TENANT="$HTENANT" IDP_E2E_HOST_SECRET="$IDP_DEV_SECRET" IDP_E2E_MODEL="$MODEL" IDP_E2E_MODEL_NAME="$MODEL_NAME" \
IDP_E2E_MODE="$MODE" IDP_E2E_KEYCLOAK="$ISSUER" IDP_E2E_KEYCLOAK_CLIENTS="$PWD/.local/keycloak-clients.json" \
IDP_E2E_REGISTRY="$REG" IDP_E2E_MCP_TENANT="$TENANT" IDP_E2E_MCP_SECRET="$IDP_DEV_ADMIN_SECRET" \
IDP_E2E_METRICS=http://127.0.0.1:9465/metrics IDP_E2E_WORKER_METRICS=http://127.0.0.1:9466/metrics \
  go test -count=1 -v -run '^TestComposeHost$' ./tests/e2e/
status=$?
set -e
[[ $status == 0 ]] || "${C[@]}" logs --tail 40 host host-worker mcp-gateway registry keycloak 2>/dev/null
exit $status
